export function icon(name, options = {}) {
  const {
    size = 18,
    className = "",
    strokeWidth = 1.8,
    label = "",
    extra = ""
  } = options;
  const paths = ICON_PATHS[name];
  const classAttr = className ? ` class="${className}"` : "";
  const labelAttr = label ? ` role="img" aria-label="${label}"` : ' aria-hidden="true"';
  if (!paths) {
    return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round"${classAttr}${labelAttr}><circle cx="12" cy="12" r="9"/></svg>`;
  }
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round"${classAttr}${labelAttr}${extra}>${paths}</svg>`;
}

export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((element) => {
    const name = element.dataset.icon;
    const size = Number(element.dataset.iconSize || 18);
    element.innerHTML = icon(name, { size });
  });
}

export function hasIcon(name) {
  return Boolean(ICON_PATHS[name]);
}
